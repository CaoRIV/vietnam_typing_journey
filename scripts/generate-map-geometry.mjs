import fs from "node:fs";
import path from "node:path";
import { geoMercator, geoPath } from "d3-geo";

const VIEWBOX = { width: 480, height: 720 };
const FIT_EXTENT = [
  [36, 26],
  [444, 694],
];
const BOUNDARY_PATH = path.resolve("src/data/vietnam-boundary.geo.json");
const ROUTE_PATH = path.resolve("src/data/centralRoute.geo.json");
const OUTPUT_PATH = path.resolve("src/data/mapGeometry.generated.ts");

const boundary = JSON.parse(fs.readFileSync(BOUNDARY_PATH, "utf8"));
const routeSource = JSON.parse(fs.readFileSync(ROUTE_PATH, "utf8"));
const projection = geoMercator().fitExtent(FIT_EXTENT, boundary);
const pathGenerator = geoPath(projection).digits(2);
const mapPath = pathGenerator(boundary);

if (!mapPath) throw new Error("Could not create an SVG path from Vietnam GeoJSON.");

const project = (coordinates) => {
  const projected = projection(coordinates);
  if (!projected) throw new Error(`Could not project ${coordinates.join(", ")}`);
  return { x: Number(projected[0].toFixed(2)), y: Number(projected[1].toFixed(2)) };
};

const routePoints = routeSource.route.map((waypoint) => project(waypoint.coordinates));
const stops = routeSource.stops.map((stop) => {
  const pointIndex = routeSource.route.findIndex((waypoint) => waypoint.stopId === stop.id);
  if (pointIndex < 0) throw new Error(`Route waypoint is missing for stop: ${stop.id}`);

  const point = routePoints[pointIndex];
  return {
    id: stop.id,
    name: stop.name,
    coordinates: stop.coordinates,
    pointIndex,
    label: {
      x: Number((point.x + stop.label.dx).toFixed(2)),
      y: Number((point.y + stop.label.dy).toFixed(2)),
      anchor: stop.label.anchor,
    },
  };
});

const archipelagos = routeSource.archipelagos.map((place) => {
  const point = project(place.coordinates);
  return {
    id: place.id,
    name: place.name,
    coordinates: place.coordinates,
    point,
    label: {
      x: Number((point.x + place.label.dx).toFixed(2)),
      y: Number((point.y + place.label.dy).toFixed(2)),
      anchor: place.label.anchor,
    },
  };
});

const generated = {
  source: boundary.properties,
  viewBox: VIEWBOX,
  fitExtent: FIT_EXTENT,
  projection: {
    type: "geoMercator",
    scale: Number(projection.scale().toFixed(8)),
    translate: projection.translate().map((value) => Number(value.toFixed(8))),
    center: projection.center(),
  },
  mapPath,
  route: {
    id: routeSource.id,
    name: routeSource.name,
    region: routeSource.region,
    geoPoints: routeSource.route.map((waypoint) => waypoint.coordinates),
    points: routePoints,
    stops,
  },
  archipelagos,
};

const output = `// Generated by scripts/generate-map-geometry.mjs. Do not edit by hand.\nexport const generatedMapGeometry = ${JSON.stringify(generated, null, 2)} as const;\n`;
fs.writeFileSync(OUTPUT_PATH, output);
console.log(`Generated ${OUTPUT_PATH} (${mapPath.length} SVG path characters)`);
