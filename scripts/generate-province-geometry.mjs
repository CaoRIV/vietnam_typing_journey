const sourceRoot =
  "https://raw.githubusercontent.com/thanglequoc/vietnamese-provinces-database/master/json/geojson";

const fetchProvince = async ([code, slug]) => {
  const directory = `${code}_${slug.replaceAll("-", "_")}`;
  const url = `${sourceRoot}/${directory}/${directory}.geojson`;
  const response = await fetch(url, {
    headers: { "User-Agent": "Go-Xuyen-Viet/1.0" },
  });

  if (!response.ok) {
    throw new Error(`Could not fetch ${url}: ${response.status}`);
  }

  const collection = await response.json();
  const feature = collection.features?.[0];
  if (!feature?.geometry) {
    throw new Error(`No province geometry found in ${url}`);
  }

  return { code, slug, url, feature };
};

const squareDistanceToSegment = (point, start, end) => {
  let x = start[0];
  let y = start[1];
  let dx = end[0] - x;
  let dy = end[1] - y;

  if (dx !== 0 || dy !== 0) {
    const offset =
      ((point[0] - x) * dx + (point[1] - y) * dy) / (dx * dx + dy * dy);
    if (offset > 1) {
      x = end[0];
      y = end[1];
    } else if (offset > 0) {
      x += dx * offset;
      y += dy * offset;
    }
  }

  dx = point[0] - x;
  dy = point[1] - y;
  return dx * dx + dy * dy;
};

const simplifyLine = (points, tolerance) => {
  if (points.length <= 3) {
    return points;
  }

  const squareTolerance = tolerance * tolerance;
  const markers = new Uint8Array(points.length);
  const stack = [[0, points.length - 1]];
  markers[0] = 1;
  markers[points.length - 1] = 1;

  while (stack.length) {
    const [first, last] = stack.pop();
    let maxDistance = squareTolerance;
    let index = 0;

    for (let cursor = first + 1; cursor < last; cursor += 1) {
      const distance = squareDistanceToSegment(
        points[cursor],
        points[first],
        points[last],
      );
      if (distance > maxDistance) {
        index = cursor;
        maxDistance = distance;
      }
    }

    if (index) {
      markers[index] = 1;
      stack.push([first, index], [index, last]);
    }
  }

  return points.filter((_, index) => markers[index]);
};

const number = (value) => Number(value.toFixed(1));
const pointText = ([x, y]) => `${number(x)},${number(y)}`;

const ringToPath = (ring, projection) => {
  const projected = ring
    .map((coordinate) => projection(coordinate))
    .filter(Boolean)
    .map(([x, y]) => [x, y]);
  if (projected.length < 4) {
    return "";
  }

  const openRing = projected.slice(0, -1);
  const simplified = simplifyLine(openRing, 0.42);
  if (simplified.length < 3) {
    return "";
  }

  return `M${simplified.map(pointText).join("L")}Z`;
};

const geometryToPath = (geometry, projection) => {
  const polygons =
    geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
  return polygons
    .flatMap((polygon) => polygon.map((ring) => ringToPath(ring, projection)))
    .join("");
};

const entries = await Promise.all(provinces.map(fetchProvince));
const collection = {
  type: "FeatureCollection",
  features: entries.map(({ feature }) => feature),
};
const projection = geoMercator().fitExtent(
  [
    [34, 24],
    [566, 976],
  ],
  collection,
);

const generated = entries.map(({ code, slug, url, feature }) => {
  const centroid = projection(geoCentroid(feature));
  return {
    code,
    slug,
    name: feature.properties.name,
    path: geometryToPath(feature.geometry, projection),
    label: {
      x: number(centroid[0]),
      y: number(centroid[1]),
    },
    sourceUrl: url,
  };
});

